import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import data from './content.mjs';

const root = path.resolve(import.meta.dirname, '..');
const exists = file => fs.existsSync(path.join(root, file));
const normalize = href => href.replace(/^\//, '').split('?')[0].split('#')[0];
let checked=0;
const problems=[];
for(const node of data.sitemapNodes){
  for(const lang of ['ru','en']){
    const route = lang === 'ru' ? node.url_ru : node.url_en;
    const filename=route.endsWith('.html')?normalize(route):path.join(normalize(route),'index.html');
    if(!exists(filename)){problems.push('Missing route: '+filename);continue;}
    const html=fs.readFileSync(path.join(root,filename),'utf8');
    checked++;
    if(!html.includes('<html lang="'+lang+'"'))problems.push('Locale mismatch: '+filename);
    if(!html.includes('hreflang="ru"')||!html.includes('hreflang="en"'))problems.push('Missing hreflang: '+filename);
    if(!html.includes('rel="canonical"'))problems.push('Missing canonical: '+filename);
    if(/demo only|generated by ai|Сайт в подготовке|Демонстрация/i.test(html))problems.push('Unapproved copy: '+filename);
    for(const match of html.matchAll(/(?:href|src)="(\/[^"#?]+)"/g)){
      const href=match[1];if(href.endsWith('/')){if(!exists(path.join(normalize(href),'index.html')))problems.push(filename+' -> '+href);}
      else if(!exists(normalize(href)))problems.push(filename+' -> '+href);
    }
  }
}
for(const asset of ['assets/site.css','assets/site.js','assets/photos/workshop-collage.webp','assets/photos/hero-warehouse.webp'])
 if(!exists(asset))problems.push('Missing asset: '+asset);
assert.equal(checked,60,'Expected 60 pages');
if(problems.length){console.error(problems.join('\n'));process.exit(1);}
console.log('PASS:',checked,'bilingual HTML pages; internal links, language, SEO metadata and assets.');
